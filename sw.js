// Minimal service worker for the Operations Management Study Companion.
// Its only job is to let the app show notifications reliably (especially on iOS
// home-screen installs) via registration.showNotification(). It does not cache
// files or enable offline use, and it cannot wake the app up on its own schedule.

self.addEventListener('install', (event) => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ('focus' in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow('./');
    })
  );
});
